#include "Compiler.h"
#include "Generator.h"
#include <iomanip>

std::ostringstream Gear::Generator::g_DataSection;
std::ostringstream Gear::Generator::g_TextSection;
std::map<std::string, Gear::Generator::GLOBAL_VAR_INFO> Gear::Generator::g_GlobalVars;
bool Gear::Generator::g_HasUserMain = false;
bool Gear::Generator::g_NeedsPrint = false;
int Gear::Generator::g_LabelCounter = 0;

void Gear::Generator::Reset()
{
	g_DataSection.str("");
	g_DataSection.clear();
	g_TextSection.str("");
	g_TextSection.clear();
	g_GlobalVars.clear();
	g_HasUserMain = false;
	g_NeedsPrint = false;
	g_LabelCounter = 0;
}

std::string Gear::Generator::NewLabel(const std::string& prefix)
{
	return prefix + "_" + std::to_string(g_LabelCounter++);
}

void Gear::Generator::DefineGlobalVar(const std::string& name, uint64_t init_val, uint32_t size)
{
	g_GlobalVars[name] = { init_val, size };
}

void Gear::Generator::EnsureGlobalVar(const std::string& name)
{
	if (g_GlobalVars.find(name) == g_GlobalVars.end())
	{
		g_GlobalVars[name] = { 0, 8 };
	}
}

bool Gear::Generator::IsGlobalVar(const std::string& name)
{
	return g_GlobalVars.find(name) != g_GlobalVars.end();
}

void Gear::Generator::EmitLine(const std::string& line)
{
	g_TextSection << "    " << line << "\n";
}

void Gear::Generator::EmitLabel(const std::string& label)
{
	g_TextSection << label << ":\n";
}

void Gear::Generator::EmitComment(const std::string& comment)
{
	g_TextSection << "    ; " << comment << "\n";
}

void Gear::Generator::EmitPrintRax()
{
	g_NeedsPrint = true;
	EmitComment("print RAX to stdout via C runtime printf");
	EmitLine("sub rsp, 32");
	EmitLine("mov rdx, rax");
	EmitLine("mov r8, rax");
	EmitLine("lea rcx, [__gear_fmt_val]");
	EmitLine("call printf");
	EmitLine("add rsp, 32");
}

std::string Gear::Generator::GetOutput()
{
	std::ostringstream out;
	out << "; ============================================================\n";
	out << "; Generated by Gear Compiler\n";
	out << "; Target: x86-64 MASM (Windows x64 ABI)\n";
	out << "; ============================================================\n\n";

	// C Runtime declarations for print/main support
	if (g_NeedsPrint || g_HasUserMain)
	{
		out << "INCLUDELIB msvcrt.lib\n";
		out << "INCLUDELIB legacy_stdio_definitions.lib\n";
		out << "EXTERN printf : PROC\n\n";
	}

	// Data section with all global variables & format strings
	out << ".data\n";
	if (g_NeedsPrint)
	{
		out << "    __gear_fmt_val DB \"[Gear Output] 0x%llX (%lld)\", 0Ah, 0\n";
	}

	if (!g_GlobalVars.empty())
	{
		for (const auto& [name, info] : g_GlobalVars)
		{
			out << "PUBLIC " << name << "\n";
			if (info.size > 8)
			{
				out << name << " DB " << info.size << " DUP(0)\n";
			}
			else
			{
				std::string type_dir = "QWORD";
				if (info.size == 1) type_dir = "BYTE";
				else if (info.size == 2) type_dir = "WORD";
				else if (info.size == 4) type_dir = "DWORD";

				out << name << " " << type_dir << " ";
				if (info.init_val > 0)
				{
					out << "0" << std::hex << std::uppercase << info.init_val << "h\n";
					out << std::dec;
				}
				else
				{
					out << "0\n";
				}
			}
		}
	}
	out << "\n";

	out << ".code\n\n";
	out << g_TextSection.str();
	out << "\nEND\n";
	return out.str();
}
